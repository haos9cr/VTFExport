# embed_lang.ps1 - turns every lang\*.lang file into a byte array that is
# compiled into the plug-in (included by src\Lang.cpp). Run by the pre-build
# step of VTFExport.vcxproj; the output is only rewritten when it changes.
param(
    [Parameter(Mandatory = $true)][string]$LangDir,
    [Parameter(Mandatory = $true)][string]$Out
)
$ErrorActionPreference = 'Stop'

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools/embed_lang.ps1 from the lang folder - do not edit.')
$files = @()
if (Test-Path -LiteralPath $LangDir) {
    $files = @(Get-ChildItem -LiteralPath $LangDir -Filter '*.lang' -File | Sort-Object Name)
}
$i = 0
foreach ($f in $files) {
    $bytes = [System.IO.File]::ReadAllBytes($f.FullName)
    [void]$sb.AppendLine("// $($f.Name)")
    [void]$sb.Append("static const unsigned char kLang$i[] = {")
    for ($j = 0; $j -lt $bytes.Length; $j++) {
        if ($j % 32 -eq 0) { [void]$sb.Append("`n ") }
        [void]$sb.Append($bytes[$j]).Append(',')
    }
    [void]$sb.AppendLine('0};')
    $i++
}
[void]$sb.AppendLine('static const EmbeddedLang kEmbeddedLangs[] = {')
for ($k = 0; $k -lt $i; $k++) { [void]$sb.AppendLine("    {kLang$k, sizeof(kLang$k) - 1},") }
[void]$sb.AppendLine('    {nullptr, 0},')
[void]$sb.AppendLine('};')

$text = $sb.ToString()
$old = $null
if (Test-Path -LiteralPath $Out) { $old = [System.IO.File]::ReadAllText($Out) }
if ($old -ne $text) {
    $dir = Split-Path -Parent $Out
    if ($dir -and -not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
    [System.IO.File]::WriteAllText($Out, $text, (New-Object System.Text.UTF8Encoding $false))
}
Write-Host "embed_lang: $i language file(s) embedded"
