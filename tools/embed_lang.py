"""Same as embed_lang.ps1 (for building/testing outside Visual Studio).
Usage: python3 embed_lang.py <lang dir> <output .inc>"""
import sys
from pathlib import Path

lang_dir, out = Path(sys.argv[1]), Path(sys.argv[2])
lines = ["// Generated by tools/embed_lang.py from the lang folder - do not edit."]
files = sorted(lang_dir.glob("*.lang"), key=lambda p: p.name) if lang_dir.is_dir() else []
for i, f in enumerate(files):
    data = f.read_bytes()
    lines.append(f"// {f.name}")
    body = ",".join(str(b) for b in data)
    lines.append(f"static const unsigned char kLang{i}[] = {{{body}{',' if data else ''}0}};")
lines.append("static const EmbeddedLang kEmbeddedLangs[] = {")
lines += [f"    {{kLang{i}, sizeof(kLang{i}) - 1}}," for i in range(len(files))]
lines += ["    {nullptr, 0},", "};"]
text = "\n".join(lines) + "\n"
if not out.exists() or out.read_text() != text:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
print(f"embed_lang: {len(files)} language file(s) embedded")
